"use client";

/** Chords for the ambient pad (Hz): A minor add9, F major 7, C add9, G6. Slow and quiet, decoration only. */
const CHORDS = [
  [110, 164.81, 246.94, 261.63],
  [87.31, 174.61, 220, 261.63],
  [130.81, 196, 293.66, 329.63],
  [98, 146.83, 246.94, 329.63],
];
const CHORD_S = 8;
const MUSIC_LEVEL = 0.05;
const DUCKED = 0.4;

/** What the show tells its sound: the live soundscape plays it, a recording logs it. */
export interface SoundOut {
  start(): void;
  click(): void;
  whoosh(): void;
  /** One key of the keyboard while a question is typed (the space bar sounds deeper). */
  key(space?: boolean): void;
  /** VESTA flies in: a rising whoosh. */
  rise(): void;
  /** Her sunglasses land: a short sparkle. */
  sparkle(): void;
  /** She pops into her window or back into mini VESTA. */
  pop(): void;
  duck(speaking: boolean): void;
  setMusic(on: boolean): void;
  setSfx(on: boolean): void;
  stop(): void;
}

/** A sound in a recording, `at` seconds from its start. */
export interface SoundEvent {
  type: "click" | "whoosh" | "key" | "space" | "rise" | "sparkle" | "pop" | "duck";
  at: number;
  on?: boolean;
}

/**
 * Sound for the presentation, all generated by the browser (no audio files): soft click ticks, a whoosh for
 * page changes and a quiet space-ambient pad that softens while the voice speaks. Live it plays as it goes;
 * for the recorded show the same sounds are rendered into a track at the moments they happened.
 */
export class Soundscape implements SoundOut {
  sfxOn: boolean;
  musicOn: boolean;
  private ctx: BaseAudioContext | null = null;
  private readonly given: OfflineAudioContext | null;
  private sfx: GainNode | null = null;
  private music: GainNode | null = null;
  private oscs: OscillatorNode[] = [];
  private noise: AudioBuffer | null = null;
  private chordTimer: ReturnType<typeof setInterval> | null = null;
  private ducked = false;

  constructor(sfxOn: boolean, musicOn: boolean, offline: OfflineAudioContext | null = null) {
    this.sfxOn = sfxOn;
    this.musicOn = musicOn;
    this.given = offline;
  }

  start() {
    if (this.ctx) return;
    if (this.given) this.ctx = this.given;
    else {
      const Ctx = typeof window !== "undefined" ? (window.AudioContext ?? (window as unknown as { webkitAudioContext?: typeof AudioContext }).webkitAudioContext) : undefined;
      if (!Ctx) return;
      try {
        const live = new Ctx();
        void live.resume();
        this.ctx = live;
      } catch {
        return;
      }
    }
    const ctx = this.ctx;
    this.sfx = ctx.createGain();
    this.sfx.gain.value = this.sfxOn ? 1 : 0;
    this.sfx.connect(ctx.destination);
    const len = Math.floor(ctx.sampleRate * 1.2);
    this.noise = ctx.createBuffer(1, len, ctx.sampleRate);
    const d = this.noise.getChannelData(0);
    for (let i = 0; i < len; i++) d[i] = Math.random() * 2 - 1;
    this.startMusic();
  }

  private startMusic() {
    const ctx = this.ctx;
    if (!ctx) return;
    this.music = ctx.createGain();
    this.music.gain.value = 0;
    const filter = ctx.createBiquadFilter();
    filter.type = "lowpass";
    filter.frequency.value = 900;
    filter.Q.value = 0.7;
    // a slow sweep of the filter keeps the pad alive
    const lfo = ctx.createOscillator();
    const lfoGain = ctx.createGain();
    lfo.frequency.value = 0.06;
    lfoGain.gain.value = 320;
    lfo.connect(lfoGain).connect(filter.frequency);
    lfo.start();
    // a soft echo for space
    const delay = ctx.createDelay(1);
    delay.delayTime.value = 0.38;
    const fb = ctx.createGain();
    fb.gain.value = 0.32;
    filter.connect(this.music);
    filter.connect(delay);
    delay.connect(fb).connect(delay);
    delay.connect(this.music);
    this.music.connect(ctx.destination);
    CHORDS[0].forEach((f, i) => {
      const o = ctx.createOscillator();
      o.type = i % 2 ? "sine" : "triangle";
      o.frequency.value = f;
      o.detune.value = (i - 1.5) * 4;
      const g = ctx.createGain();
      g.gain.value = 0.22;
      o.connect(g).connect(filter);
      o.start();
      this.oscs.push(o);
    });
    this.oscs.push(lfo);
    const change = (n: number, at: number) => CHORDS[n % CHORDS.length].forEach((f, i) => this.oscs[i]?.frequency.setTargetAtTime(f, at, 1.2));
    if (this.given) {
      // a recording knows its length: lay out every chord change up front
      const seconds = this.given.length / this.given.sampleRate;
      for (let n = 1; n * CHORD_S < seconds; n++) change(n, n * CHORD_S);
    } else {
      let n = 0;
      this.chordTimer = setInterval(() => change(++n, ctx.currentTime), CHORD_S * 1000);
    }
    this.applyMusicLevel(2.5, 0);
  }

  private applyMusicLevel(fade = 0.4, at?: number) {
    if (!this.ctx || !this.music) return;
    const level = this.musicOn ? MUSIC_LEVEL * (this.ducked ? DUCKED : 1) : 0;
    this.music.gain.setTargetAtTime(level, at ?? this.ctx.currentTime, fade / 3);
  }

  /** The voice is speaking: the music steps back. */
  duck(speaking: boolean, at?: number) {
    this.ducked = speaking;
    this.applyMusicLevel(0.5, at);
  }

  setMusic(on: boolean) {
    this.musicOn = on;
    this.applyMusicLevel(0.6);
  }

  setSfx(on: boolean) {
    this.sfxOn = on;
    if (this.ctx && this.sfx) this.sfx.gain.setTargetAtTime(on ? 1 : 0, this.ctx.currentTime, 0.05);
  }

  /** A soft tick for clicks. */
  click(at?: number) {
    const ctx = this.ctx;
    if (!ctx || !this.sfx || !this.sfxOn) return;
    const t = at ?? ctx.currentTime;
    const o = ctx.createOscillator();
    const g = ctx.createGain();
    o.type = "sine";
    o.frequency.setValueAtTime(1400, t);
    o.frequency.exponentialRampToValueAtTime(700, t + 0.06);
    g.gain.setValueAtTime(0.0001, t);
    g.gain.exponentialRampToValueAtTime(0.09, t + 0.005);
    g.gain.exponentialRampToValueAtTime(0.0001, t + 0.08);
    o.connect(g).connect(this.sfx);
    o.start(t);
    o.stop(t + 0.1);
  }

  /** A light whoosh for page changes. */
  whoosh(at?: number) {
    const ctx = this.ctx;
    if (!ctx || !this.sfx || !this.noise || !this.sfxOn) return;
    const t = at ?? ctx.currentTime;
    const src = ctx.createBufferSource();
    src.buffer = this.noise;
    const bp = ctx.createBiquadFilter();
    bp.type = "bandpass";
    bp.Q.value = 1.2;
    bp.frequency.setValueAtTime(280, t);
    bp.frequency.exponentialRampToValueAtTime(2400, t + 0.42);
    const g = ctx.createGain();
    g.gain.setValueAtTime(0.0001, t);
    g.gain.exponentialRampToValueAtTime(0.12, t + 0.12);
    g.gain.exponentialRampToValueAtTime(0.0001, t + 0.5);
    src.connect(bp).connect(g).connect(this.sfx);
    src.start(t);
    src.stop(t + 0.55);
  }

  /** A keyboard key: the click of the keycap (a tiny band of noise) and the soft thock as it bottoms out. */
  key(space = false, at?: number) {
    const ctx = this.ctx;
    if (!ctx || !this.sfx || !this.noise || !this.sfxOn) return;
    const t = at ?? ctx.currentTime;
    const vary = 0.8 + Math.random() * 0.4;
    const src = ctx.createBufferSource();
    src.buffer = this.noise;
    const bp = ctx.createBiquadFilter();
    bp.type = "bandpass";
    bp.Q.value = 2.2;
    bp.frequency.value = space ? 1300 : 2500 + Math.random() * 1500;
    const g = ctx.createGain();
    g.gain.setValueAtTime(0.0001, t);
    g.gain.exponentialRampToValueAtTime((space ? 0.1 : 0.065) * vary, t + 0.002);
    g.gain.exponentialRampToValueAtTime(0.0001, t + (space ? 0.05 : 0.03));
    src.connect(bp).connect(g).connect(this.sfx);
    src.start(t, Math.random() * 0.8);
    src.stop(t + 0.07);
    const o = ctx.createOscillator();
    const og = ctx.createGain();
    o.type = "sine";
    o.frequency.setValueAtTime(space ? 140 : 210, t);
    o.frequency.exponentialRampToValueAtTime(space ? 70 : 110, t + 0.04);
    og.gain.setValueAtTime(0.0001, t);
    og.gain.exponentialRampToValueAtTime((space ? 0.08 : 0.045) * vary, t + 0.003);
    og.gain.exponentialRampToValueAtTime(0.0001, t + 0.06);
    o.connect(og).connect(this.sfx);
    o.start(t);
    o.stop(t + 0.08);
  }

  /** VESTA flies in: noise sweeping up with a soft rising tone. */
  rise(at?: number) {
    const ctx = this.ctx;
    if (!ctx || !this.sfx || !this.noise || !this.sfxOn) return;
    const t = at ?? ctx.currentTime;
    const src = ctx.createBufferSource();
    src.buffer = this.noise;
    const bp = ctx.createBiquadFilter();
    bp.type = "bandpass";
    bp.Q.value = 1.4;
    bp.frequency.setValueAtTime(300, t);
    bp.frequency.exponentialRampToValueAtTime(3200, t + 0.85);
    const g = ctx.createGain();
    g.gain.setValueAtTime(0.0001, t);
    g.gain.exponentialRampToValueAtTime(0.12, t + 0.5);
    g.gain.exponentialRampToValueAtTime(0.0001, t + 0.95);
    src.connect(bp).connect(g).connect(this.sfx);
    src.start(t);
    src.stop(t + 1);
    const o = ctx.createOscillator();
    const og = ctx.createGain();
    o.type = "sine";
    o.frequency.setValueAtTime(260, t);
    o.frequency.exponentialRampToValueAtTime(780, t + 0.8);
    og.gain.setValueAtTime(0.0001, t);
    og.gain.exponentialRampToValueAtTime(0.035, t + 0.6);
    og.gain.exponentialRampToValueAtTime(0.0001, t + 0.95);
    o.connect(og).connect(this.sfx);
    o.start(t);
    o.stop(t + 1);
  }

  /** The sunglasses land: four quick high notes. */
  sparkle(at?: number) {
    const ctx = this.ctx;
    if (!ctx || !this.sfx || !this.sfxOn) return;
    const t0 = at ?? ctx.currentTime;
    [1318.5, 1661.2, 1975.5, 2637].forEach((f, i) => {
      const t = t0 + i * 0.07;
      const o = ctx.createOscillator();
      const g = ctx.createGain();
      o.type = "triangle";
      o.frequency.value = f;
      g.gain.setValueAtTime(0.0001, t);
      g.gain.exponentialRampToValueAtTime(0.045, t + 0.006);
      g.gain.exponentialRampToValueAtTime(0.0001, t + 0.35);
      o.connect(g).connect(this.sfx!);
      o.start(t);
      o.stop(t + 0.4);
    });
  }

  /** A soft, bubbly pop. */
  pop(at?: number) {
    const ctx = this.ctx;
    if (!ctx || !this.sfx || !this.sfxOn) return;
    const t = at ?? ctx.currentTime;
    const o = ctx.createOscillator();
    const g = ctx.createGain();
    o.type = "sine";
    o.frequency.setValueAtTime(520, t);
    o.frequency.exponentialRampToValueAtTime(170, t + 0.12);
    g.gain.setValueAtTime(0.0001, t);
    g.gain.exponentialRampToValueAtTime(0.12, t + 0.008);
    g.gain.exponentialRampToValueAtTime(0.0001, t + 0.16);
    o.connect(g).connect(this.sfx);
    o.start(t);
    o.stop(t + 0.18);
  }

  /** The music fades away over the last seconds of a recording. */
  fadeOut(at: number, seconds: number) {
    if (this.music) this.music.gain.setTargetAtTime(0, at, seconds / 3);
  }

  stop() {
    if (this.chordTimer) clearInterval(this.chordTimer);
    this.chordTimer = null;
    const ctx = this.ctx;
    this.ctx = null;
    this.music = null;
    this.sfx = null;
    if (!ctx || this.given || !("close" in ctx)) return;
    const live = ctx as AudioContext;
    setTimeout(() => {
      this.oscs.forEach((o) => {
        try {
          o.stop();
        } catch {
          /* already stopped */
        }
      });
      this.oscs = [];
      void live.close();
    }, 1200);
  }
}

/**
 * While the demo video is recorded nothing is played: each click, whoosh and duck is written down with its
 * moment on the page's clock (seconds), and the track is rendered afterwards with `renderSoundtrack`.
 */
export class SoundLog implements SoundOut {
  events: SoundEvent[] = [];
  private log(type: SoundEvent["type"], on?: boolean) {
    this.events.push({ type, at: performance.now() / 1000, ...(on === undefined ? {} : { on }) });
  }
  start() {}
  click() {
    this.log("click");
  }
  whoosh() {
    this.log("whoosh");
  }
  key(space = false) {
    this.log(space ? "space" : "key");
  }
  rise() {
    this.log("rise");
  }
  sparkle() {
    this.log("sparkle");
  }
  pop() {
    this.log("pop");
  }
  duck(speaking: boolean) {
    this.log("duck", speaking);
  }
  setMusic() {}
  setSfx() {}
  stop() {}
}

/**
 * The recorded show's music and sound effects as one mono track: the same pad, ticks and whooshes as the
 * live show, rendered offline at the moments the recording logged them.
 */
export async function renderSoundtrack(events: SoundEvent[], seconds: number, sampleRate = 44100): Promise<Float32Array> {
  const ctx = new OfflineAudioContext(1, Math.ceil(seconds * sampleRate), sampleRate);
  const s = new Soundscape(true, true, ctx);
  s.start();
  for (const e of [...events].sort((a, b) => a.at - b.at)) {
    if (e.type === "click") s.click(e.at);
    else if (e.type === "whoosh") s.whoosh(e.at);
    else if (e.type === "key" || e.type === "space") s.key(e.type === "space", e.at);
    else if (e.type === "rise") s.rise(e.at);
    else if (e.type === "sparkle") s.sparkle(e.at);
    else if (e.type === "pop") s.pop(e.at);
    else s.duck(!!e.on, e.at);
  }
  s.fadeOut(Math.max(0, seconds - 3), 2.5);
  const buf = await ctx.startRendering();
  return buf.getChannelData(0);
}
